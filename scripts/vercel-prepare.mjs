// Vercel build step: derive the PostgreSQL schema from the SQLite one (single source of truth) and
// create the baseline migration once. Local dev and tests keep using SQLite.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execSync } from "node:child_process";

mkdirSync("prisma/pg", { recursive: true });
const schema = readFileSync("prisma/schema.prisma", "utf8").replace('provider = "sqlite"', 'provider = "postgresql"');
writeFileSync("prisma/pg/schema.prisma", schema);
if (!existsSync("prisma/pg/migrations")) {
  mkdirSync("prisma/pg/migrations/0_init", { recursive: true });
  const sql = execSync("npx prisma migrate diff --from-empty --to-schema-datamodel prisma/pg/schema.prisma --script", { encoding: "utf8" });
  writeFileSync("prisma/pg/migrations/0_init/migration.sql", sql);
  writeFileSync("prisma/pg/migrations/migration_lock.toml", '# Please do not edit this file manually\nprovider = "postgresql"\n');
}
